    fun variantsOf(t: String): List<String> {
        val out = LinkedHashSet<String>()
        out.add(t)
        fun addAl(x: String) {
            out.add(x)
            if (x.startsWith("ال") && x.length > 3) out.add(x.substring(2))
            if (x.startsWith("لل") && x.length > 3) out.add(x.substring(2))
        }
        addAl(t)
        if (t.length > 3 && (t[0] == 'و' || t[0] == 'ب' || t[0] == 'ل' || t[0] == 'ف' || t[0] == 'ك')) {
            val r = t.substring(1)
            addAl(r)
        }
        if (t.length > 4 && (t.startsWith("وال") || t.startsWith("بال") || t.startsWith("فال") || t.startsWith("كال"))) {
            out.add(t.substring(3))
        }
        return out.toList()
    }

    fun isStop(t: String): Boolean = variantsOf(t).any { it in ALL }
